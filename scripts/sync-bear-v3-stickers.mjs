import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const source = path.join(root, "表情包资料/双端表情包-V3-全动态");
const manifest = JSON.parse(await readFile(path.join(source, "manifest/全动态素材清单-v3.json"), "utf8"));
if (manifest.length !== 70 || new Set(manifest.map(item => item.key)).size !== 70) throw new Error("V3 清单必须包含 70 个唯一表情");
const entries = [];
for (const item of manifest) {
  const side = item.side === "买家端" ? "buyer" : item.side === "卖家端" ? "seller" : null;
  if (!side || !/^\w+-\d{3}$/.test(item.key) || item.width !== 384 || item.height !== 384 || item.duration_ms !== 2800 || !item.true_transparency) throw new Error(`非最终 V3 素材：${item.key}`);
  const filename = path.basename(item.path);
  const input = path.join(source, "exports/GIF", item.side, filename);
  const bytes = await readFile(input);
  if (createHash("sha256").update(bytes).digest("hex") !== item.sha256 || bytes.subarray(0, 6).toString() !== "GIF89a") throw new Error(`素材校验失败：${item.key}`);
  const url = `/assets/chat-stickers/bear-v3/${side}/${item.key}.gif`;
  const output = path.join(root, "public", url);
  await mkdir(path.dirname(output), { recursive: true });
  await copyFile(input, output);
  entries.push({ id: `bear-v3/${side}/${item.key.slice(-3)}`, name: item.text, side, url, width: 384, height: 384, duration_ms: 2800, frames: item.frames, sha256: item.sha256, bytes: bytes.length });
}
for (const side of ["buyer", "seller"]) if (entries.filter(item => item.side === side).length !== 35) throw new Error(`${side} 不是 35 个`);
await writeFile(path.join(root, "public/assets/chat-stickers/bear-v3/manifest.json"), JSON.stringify(entries, null, 2) + "\n");
await writeFile(path.join(root, "packages/contracts/src/bear-sticker-assets.ts"), `// Generated by scripts/sync-bear-v3-stickers.mjs from the confirmed V3 GIF manifest.\nexport const bearStickerAssets = ${JSON.stringify(entries, null, 2)} as const;\n`);
await writeFile(path.join(root, "public/assets/chat-stickers/bear-v3/README.txt"), "熊崽双端表情包 V3 最终原版 GIF，买家/卖家各35个。\n原始素材和完整制作清单保留在项目 表情包资料/双端表情包-V3-全动态。\n本目录按 SHA256 原样复制，不修改动画、透明度或文字。\n稳定ID与公开资源映射见 manifest.json；线上地址不包含本机绝对路径。\n");
console.log(JSON.stringify({ count: entries.length, buyer: 35, seller: 35, bytes: entries.reduce((sum, item) => sum + item.bytes, 0) }));
